# The pixel / retro faces of the «аркада» look → src/font_pixel.h (all six are OFL, all carry the full
# Cyrillic alphabet — that is why Press Start 2P, VT323, Silkscreen, Micro 5, Doto, Jersey and the rest of
# the usual pixel fonts are not here: they are Latin only and the Russian UI would come out empty).
# Variable fonts are instanced to static weights first (stb_truetype inside ImGui ignores the axes), then
# every face is subset to what the UI shows (Latin, Latin-1, Cyrillic, punctuation, arrows).
#   Handjet        — pixel grid, ELGR 1 / ELSH 2 (square elements); weights 400 / 700
#   Tiny5          — a true 5 px bitmap face; one weight
#   Pixelify Sans  — rounder pixels; lacks О, П, І (mapped onto Latin O, Greek Pi, Latin I) and its С is
#                    nearly identical to О, so it reads best in Latin
#   Rubik Mono One — wide arcade-cabinet display face; one weight
#   Unbounded      — techno grotesque, weights 400 / 700
#   Stalinist One  — constructivist square caps; one weight
import io, os
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

